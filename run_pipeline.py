def convert_macleod_xml_to_csv(input_xml_path, output_csv_path):
    """Parses a Macleod .mtx file into a simple, two-column CSV file."""
    try:
        # مسیر فایل ورودی را با پوشه نتایج ترکیب می‌کند
        # *** V14: فرض می‌کنیم فایل‌های .mtx هم در پوشه نتایج هستند ***
        full_input_path = os.path.join(RESULTS_DIR, input_xml_path)
        full_output_path = os.path.join(RESULTS_DIR, output_csv_path)

        if not os.path.exists(full_input_path):
            # اگر در پوشه نتایج نبود، در پوشه اصلی جستجو کن
            full_input_path = input_xml_path
            if not os.path.exists(full_input_path):
                print(f"Input file not found: {input_xml_path}. Skipping conversion.")
                return False

        # اگر فایل خروجی از قبل وجود دارد، تبدیل نکن
        if os.path.exists(full_output_path):
            print(f"Output file '{full_output_path}' already exists. Skipping conversion.")
            return True

        tree = ET.parse(full_input_path)
        root = tree.getroot()
        data_points = []
        for point in root.findall('.//NKPoint'):
            try:
                wavelength = float(point.get('W'))
                n_value = float(point.get('n'))
                data_points.append({'Wavelength': wavelength, 'n': n_value})
            except (ValueError, TypeError):
                continue
        if not data_points: return False
        df = pd.DataFrame(data_points).sort_values(by='Wavelength').reset_index(drop=True)
        df.to_csv(full_output_path, index=False, float_format='%.8f')
        print(f"Successfully converted '{full_input_path}' to '{full_output_path}'")
        return True
    except Exception as e:
        print(f"Error converting {input_xml_path}: {e}")
        return False

