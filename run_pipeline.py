def load_dl_data_from_dir(data_dir):
    """
    Helper to load datasets from their directories using REGEX.
    *** Reads P-Transmittance-Error (%) column. ***
    """
    full_data_dir = os.path.join(RESULTS_DIR, data_dir)
    X_list, Y_list, wavelengths_data = [], [], None
    if not os.path.exists(full_data_dir):
        print(f"Warning: Data directory not found: {full_data_dir}")
        return None, None, None

    print(f"Loading data from: {full_data_dir}")

    sample_pattern = re.compile(r"sample_(\d+)_angle_(-?[\d\.]+)_thickness_(-?[\d\.]+)\.csv")
    angle_pattern = re.compile(r"angle_(-?[\d\.]+)_thickness_(-?[\d\.]+)\.csv")

    for filename in os.listdir(full_data_dir):
        angle, thickness = None, None
        match = sample_pattern.match(filename)
        if match:
            angle, thickness = float(match.group(2)), float(match.group(3))
        else:
            match = angle_pattern.match(filename)
            if match:
                angle, thickness = float(match.group(1)), float(match.group(2))
            else:
                continue

        try:
            df = pd.read_csv(os.path.join(full_data_dir, filename))
            # *** CHANGED COLUMN ***
            Y_list.append(df['P-Transmittance-Error (%)'].values)
            X_list.append([angle, thickness])
            if wavelengths_data is None: wavelengths_data = df['Wavelength (nm)'].values
        except Exception as e:
            print(f"Warning: Could not read file {filename}: {e}")

    print(f"Loaded {len(X_list)} samples.")
    if len(X_list) == 0:
         print(f"CRITICAL WARNING: No files were loaded. Check file naming convention in '{full_data_dir}'!")

    return np.array(X_list, dtype=np.float32), np.array(Y_list, dtype=np.float32), wavelengths_data

# *** UPGRADE V9: Fixed focused loss (FOR MINIMIZATION) ***
def create_focused_loss(shape_weight, min_value_weight, min_location_weight):
    """
    Creates the original 3-component loss function (Shape, Value, Location)
    to MINIMIZE the Transmittance-Error.
    *** V9: Fixed by scaling the location_loss component. ***
    """
    def focused_loss(y_true, y_pred): # y_true is now T_Error
        epsilon = 1e-7

        # 1. Shape Loss: Weight = 1 / (T_Error + eps)
        y_true_safe = tf.maximum(y_true, epsilon)
        shape_weights = tf.math.divide_no_nan(1.0, y_true_safe)
        shape_loss = tf.reduce_mean(shape_weights * tf.square(y_true - y_pred))

        # 2. Min Value Loss (finds the minimum T_Error)
        min_true_val = tf.reduce_min(y_true, axis=-1)
        min_pred_val = tf.reduce_min(y_pred, axis=-1)
        min_value_loss = tf.reduce_mean(tf.square(min_true_val - min_pred_val))

        # 3. Min Location Loss (finds location of minimum T_Error)
        min_true_idx = tf.argmin(y_true, axis=-1)
        min_pred_idx = tf.argmin(y_pred, axis=-1)

        # *** V9 FIX: Scale the location loss ***
        # The indices range from 0 to 800. The squared error can be up to 800^2.
        # We must scale this error to be on the same order of magnitude as the other losses.
        # Wavelengths are 400 to 1200 nm (801 points).
        location_loss_scaler = tf.constant(801.0**2, dtype=tf.float32)

        min_location_loss = tf.reduce_mean(tf.square(
            tf.cast(min_true_idx, tf.float32) - tf.cast(min_pred_idx, tf.float32)
        )) / location_loss_scaler # <-- Divide by scaler

        total_loss = (shape_weight * shape_loss) + \
                     (min_value_weight * min_value_loss) + \
                     (min_location_weight * min_location_loss)
        return total_loss

    loss_name = f'focused_s{int(shape_weight*100)}_v{int(min_value_weight*100)}_l{int(min_location_weight*100)}'
    focused_loss.__name__ = loss_name
    return focused_loss

def spectral_angle_mapper_loss(y_true, y_pred):
    """
    Creates the Spectral Angle Mapper (SAM) loss function.
    """
    epsilon = 1e-7
    y_true_norm = tf.norm(y_true, axis=-1)
    y_pred_norm = tf.norm(y_pred, axis=-1)
    dot_product = tf.reduce_sum(y_true * y_pred, axis=-1)

    denominator = y_true_norm * y_pred_norm + epsilon
    cosine_similarity = dot_product / denominator

    cosine_similarity = tf.clip_by_value(cosine_similarity, -1.0 + epsilon, 1.0 - epsilon)
    sam_rad = tf.acos(cosine_similarity)
    return tf.reduce_mean(sam_rad)
spectral_angle_mapper_loss.__name__ = 'sam_loss'

# *** UPGRADE V11: Reverted to simple, proven V8 architecture. Removed BatchNormalization. ***
def create_dl_model(input_shape, output_shape):
    """
    Defines the robust MLP model with GaussianNoise.
    (V8 architecture, proven to be stable and effective).
    """
    return keras.Sequential([
        layers.Input(shape=input_shape),
        layers.GaussianNoise(0.02),
        layers.Dense(128, activation='relu'),
        layers.Dense(256, activation='relu'),
        layers.Dense(256, activation='relu'),
        layers.Dense(output_shape, activation='linear'), # Linear first
        layers.ReLU(max_value=100.0) # Then ReLU clip for [0, 100] T_Error
    ])

def run_single_dl_experiment(config, X_train, y_train, X_val, y_val, scaler, wavelengths, material_config):
    """
    Runs one full training and evaluation cycle on T_Error.
    *** V14: Skips training if model file already exists in RESULTS_DIR. ***
    """
    config_name = config['name']
    loss_function = config['loss']

    # *** V14: All paths point to RESULTS_DIR ***
    model_filename = os.path.join(RESULTS_DIR, f"{material_config['prefix']}_model_{config_name}.h5")

    # *** INCREMENTAL CHECK: Skip if model file already exists ***
    if os.path.exists(model_filename):
        print("\n" + "-"*60 + f"\nSkipping training for: {config_name} ({material_config['name']}) - Model file already exists.\n" + "-"*60)
        return # Skip this training entirely

    print("\n" + "-"*60 + f"\nRunning DL Experiment: {config_name} ({material_config['name']})\n" + "-"*60)

    y_train_target = y_train
    y_val_target = y_val

    model = create_dl_model(input_shape=(X_train.shape[1],), output_shape=y_train_target.shape[1])

    model.compile(optimizer=keras.optimizers.Adam(learning_rate=5e-4), loss=loss_function)

    history_filename = os.path.join(RESULTS_DIR, f"{material_config['prefix']}_{config_name}_history.csv")

    callbacks = [
        EarlyStopping(monitor='val_loss', patience=100, restore_best_weights=True, verbose=1, min_delta=1e-3),
        ReduceLROnPlateau(monitor='val_loss', factor=0.5, patience=40, min_lr=1e-7, verbose=1),
        ModelCheckpoint(model_filename, save_best_only=True, monitor='val_loss')
    ]

    history = model.fit(
        X_train, y_train_target,
        validation_data=(X_val, y_val_target),
        epochs=800, # 800 is still good, EarlyStopping will handle it
        batch_size=4,
        callbacks=[callbacks],
        verbose=1
    )
    print(f"Training complete for {config_name}. Best val_loss: {np.min(history.history['val_loss']):.4f}")

    # V9: Save history for ALL models, not just one
    pd.DataFrame(history.history).to_csv(history_filename, index=False)
    print(f"Saved training history to {history_filename}")

    custom_objects = {} if isinstance(loss_function, str) else {loss_function.__name__: loss_function}
    if os.path.exists(model_filename):
        best_model = keras.models.load_model(model_filename, custom_objects=custom_objects)
        print(f"Loaded best model from {model_filename}")
    else:
        print(f"Warning: Model file {model_filename} not found after training. Using last state model.")
        best_model = model

    search_grid = np.array([[a, t] for a in np.arange(0, 61, 1) for t in np.arange(30, 151, 1)])

    # Model predicts T_Error
    predicted_error_spectra = best_model.predict(scaler.transform(search_grid), verbose=0)

    # Convert back to Transmittance for saving and analysis
    predicted_T_spectra = 100.0 - predicted_error_spectra
    predicted_T_spectra = np.clip(predicted_T_spectra, 0.0, 100.0) # Final safety clip

    # Find the spectrum with the highest peak transmittance
    optimal_spectrum_idx = np.argmax(np.max(predicted_T_spectra, axis=1))
    optimal_spectrum = predicted_T_spectra[optimal_spectrum_idx]

    pd.DataFrame({
        'Wavelength (nm)': wavelengths,
        'Predicted Transmittance (%)': optimal_spectrum
    }).to_csv(os.path.join(RESULTS_DIR, f"{material_config['prefix']}_optimal_spectrum_{config_name}.csv"), index=False)


