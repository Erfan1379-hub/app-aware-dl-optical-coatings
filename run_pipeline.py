def _load_split_for_addon(prefix, scaler):
    """Reproduce the exact train/val split (random_state=42) used everywhere else."""
    X_all, y_all, waves = load_dl_data_from_dir(f"{prefix}_data")
    if X_all is None or len(X_all) == 0:
        return None
    X_tr, X_val, y_tr, y_val = train_test_split(X_all, y_all, test_size=0.2, random_state=42)
    X_ood, y_ood, _ = load_dl_data_from_dir(f"{prefix}_ood_data")
    return {
        "X_tr": X_tr, "y_tr": y_tr,        # training pool (the 400 LHS pts)
        "X_val": X_val, "y_val": y_val,    # 100-sample validation
        "X_ood": X_ood, "y_ood": y_ood,    # 56-sample interpolative-grid (IG) test
        "waves": waves,
    }


def _nonlearning_baselines(split, method):
    """
    R3-C6: classical (non-deep-learning) surrogates fitted ONLY on the 400
    training samples, then evaluated on Val and IG sets. Operates on T_Error.
        method in {"linear", "nearest"}  ->  Linear Interp / TMM-style nearest lookup
    Returns dict of metrics on Val and IG, or None if a set is unavailable.
    """
    Xtr, ytr = split["X_tr"], split["y_tr"]

    def _predict(Xq):
        # Interpolate every spectral channel independently over the (angle, thickness) plane.
        out = np.empty((Xq.shape[0], ytr.shape[1]), dtype=np.float64)
        for ch in range(ytr.shape[1]):
            vals = _griddata(Xtr, ytr[:, ch], Xq, method=method)
            # points outside the training convex hull come back NaN -> fall back to nearest
            if np.any(np.isnan(vals)):
                nn = _griddata(Xtr, ytr[:, ch], Xq, method="nearest")
                vals = np.where(np.isnan(vals), nn, vals)
            out[:, ch] = vals
        return out

    res = {}
    for tag, Xk, yk in [("Val", split["X_val"], split["y_val"]),
                        ("IG",  split["X_ood"], split["y_ood"])]:
        if Xk is None or yk is None:
            res[tag] = None
            continue
        yp = _predict(Xk)
        res[tag] = {
            "R2":  r2_score(yk, yp),
            "MSE": mean_squared_error(yk, yp),
            "RMSE": float(np.sqrt(mean_squared_error(yk, yp))),
            "MAE": mean_absolute_error(yk, yp),
            "MaxAE": float(np.max(np.abs(yk - yp))),
        }
    return res


def _dl_full_errors(model, split):
    """Full error suite for one trained DL model, on Val and IG (T_Error domain)."""
    res = {}
    for tag, Xk, yk in [("Val", split["X_val"], split["y_val"]),
                        ("IG",  split["X_ood"], split["y_ood"])]:
        if Xk is None or yk is None:
            res[tag] = None
            continue
        # search_grid scaler was fit on raw (angle, thickness); reuse the SAME scaler
        yp = model.predict(split["_scaler"].transform(Xk), verbose=0)
        res[tag] = {
            "R2":  r2_score(yk, yp),
            "MSE": mean_squared_error(yk, yp),
            "RMSE": float(np.sqrt(mean_squared_error(yk, yp))),
            "MAE": mean_absolute_error(yk, yp),
            "MaxAE": float(np.max(np.abs(yk - yp))),
        }
    return res


def _fmt(x, nd=4):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    return f"{x:.{nd}f}"


