def create_and_save_results_table(material_config, loss_configs, custom_objects):
    """
    Generates the comprehensive results table for Transmittance Maximization.
    *** V14: Added MAE column ***
    """
    print(f"\nGenerating comprehensive results table for {material_config['name']}...")
    prefix = material_config['prefix']

    scaler_path = os.path.join(RESULTS_DIR, f"{prefix}_scaler.pkl")
    if not os.path.exists(scaler_path):
        print(f"ERROR: Scaler file not found at '{scaler_path}'. Skipping table.")
        return None
    with open(scaler_path, 'rb') as f: scaler = pickle.load(f)

    # y_val_full is T_Error
    X_val_full, y_val_full, _ = load_dl_data_from_dir(f"{prefix}_data")
    if X_val_full is None or len(X_val_full) == 0:
        print(f"ERROR: Main data not found for {prefix}. Skipping table.")
        return None
    _, X_val, _, y_val = train_test_split(X_val_full, y_val_full, test_size=0.2, random_state=42)
    X_val_scaled = scaler.transform(X_val)

    # y_ood is T_Error
    X_ood, y_ood, _ = load_dl_data_from_dir(f"{prefix}_ood_data")
    if X_ood is None or len(X_ood) == 0:
        print(f"WARNING: OOD data not found for {prefix}. Skipping OOD metrics.")
        X_ood_scaled, y_ood = None, None
    else:
        X_ood_scaled = scaler.transform(X_ood)

    results = []
    search_grid = np.array([[a, t] for a in np.arange(0, 61, 1) for t in np.arange(30, 151, 1)])
    search_grid_scaled = scaler.transform(search_grid)

    for config in loss_configs:
        model_path = os.path.join(RESULTS_DIR, f"{prefix}_model_{config['name']}.h5")
        if not os.path.exists(model_path):
            print(f"Warning: Model file '{model_path}' not found. Skipping.")
            continue

        # Handle custom object loading
        loss_name_in_file = config['loss'].__name__ if callable(config['loss']) else config['loss']
        if config['name'] == 'baseline_shape_only':
             loss_name_in_file = 'focused_s100_v0_l0'
        # *** V14: Add new hero model name ***
        elif config['name'] == 'PROPOSED_Shape+Location_v2':
             loss_name_in_file = 'focused_s95_v0_l5'

        current_custom_objects = {k: v for k, v in custom_objects.items() if k == loss_name_in_file}

        model = keras.models.load_model(model_path, custom_objects=current_custom_objects, compile=False)

        # --- 1. Validation Metrics ---
        y_pred_val = model.predict(X_val_scaled, verbose=0)
        r2_val = r2_score(y_val, y_pred_val)
        mse_val = mean_squared_error(y_val, y_pred_val)
        mae_val = mean_absolute_error(y_val, y_pred_val) # MAE اضافه شد

        # --- 2. OOD Metrics ---
        r2_ood, mse_ood, mae_ood = np.nan, np.nan, np.nan
        if X_ood_scaled is not None and y_ood is not None:
            y_pred_ood = model.predict(X_ood_scaled, verbose=0)
            r2_ood = r2_score(y_ood, y_pred_ood)
            mse_ood = mean_squared_error(y_ood, y_pred_ood)
            mae_ood = mean_absolute_error(y_ood, y_pred_ood) # MAE اضافه شد

        # --- 3. Optimization Goals ---
        all_error_spectra = model.predict(search_grid_scaled, verbose=0)
        all_T_spectra = 100.0 - all_error_spectra
        all_T_spectra = np.clip(all_T_spectra, 0.0, 100.0)

        max_transmittances = np.max(all_T_spectra, axis=1)
        avg_transmittances = np.mean(all_T_spectra, axis=1)

        peak_idx = np.argmax(max_transmittances)
        avg_idx = np.argmax(avg_transmittances)

        results.append({
            'Model': config['name'],
            'R² (Val, T_Error)': r2_val,
            'MSE (Val, T_Error)': mse_val,
            'MAE (Val, T_Error)': mae_val, # MAE اضافه شد
            'R² (OOD, T_Error)': r2_ood,
            'MSE (OOD, T_Error)': mse_ood,
            'MAE (OOD, T_Error)': mae_ood, # MAE اضافه شد
            'Peak T (%)': max_transmittances[peak_idx],
            'Peak Angle (°)': search_grid[peak_idx][0],
            'Peak Thick. (nm)': search_grid[peak_idx][1],
            'Avg T (%)': avg_transmittances[avg_idx]
        })

    df = pd.DataFrame(results)
    true_opt = material_config['true_optimum']
    title = f"Performance Comparison: {material_config['name']} (True Optimum: Angle={true_opt['angle']}°, Thickness={true_opt['thickness']}°)"

    fig_height = max(4, 0.5 * len(df) + 1.5)
    fig_width = 22 # عرض بیشتر برای گنجاندن ستون‌های MAE

    fig, ax = plt.subplots(figsize=(fig_width, fig_height)); ax.axis('off')

    cols_ordered = [
        'Model', 'R² (Val, T_Error)', 'MSE (Val, T_Error)', 'MAE (Val, T_Error)',
        'R² (OOD, T_Error)', 'MSE (OOD, T_Error)', 'MAE (OOD, T_Error)',
        'Peak T (%)', 'Peak Angle (°)', 'Peak Thick. (nm)', 'Avg T (%)'
    ]
    cols_to_plot = [col for col in cols_ordered if col in df.columns]
    df_ordered = df[cols_to_plot]

    table_data = df_ordered.map(lambda x: f'{x:.4f}' if isinstance(x, (float, np.float32, np.float64)) else x).values
    table = ax.table(cellText=table_data,
                     colLabels=df_ordered.columns, loc='center', cellLoc='center')

    table.auto_set_font_size(False); table.set_fontsize(9); table.scale(1, 1.8)
    for (i, j), cell in table.get_celld().items():
        cell.set_edgecolor('black')
        if i == 0: cell.set_text_props(weight='bold', color='white'); cell.set_facecolor('#40466e')
        else: cell.set_facecolor(['#f8f9fa', '#e9ecef'][i % 2])

    plt.title(title, weight='bold', fontsize=14, y=0.98 if len(df) > 5 else 0.9)

    output_path = os.path.join(RESULTS_DIR, f"{prefix}_results_comparison_table.png")
    plt.savefig(output_path, dpi=300, bbox_inches='tight', pad_inches=0.4)
    plt.close(fig)
    print(f"Results table saved to {output_path}")

    return df


