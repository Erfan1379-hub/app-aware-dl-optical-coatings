def calculate_transmittance(wavelength_range_nm, theta0_deg, thickness_nm, n0_func, n1_func, n2_func):
    """
    Calculates the transmittance spectrum (T = 1 - R) for P-polarization.
    """
    theta0_rad = np.deg2rad(theta0_deg)
    d = thickness_nm * 1e-9
    n0, n1, n2 = n0_func(wavelength_range_nm), n1_func(wavelength_range_nm), n2_func(wavelength_range_nm)

    with np.errstate(invalid='ignore'): # Ignore warnings for complex numbers
        theta1_rad = np.lib.scimath.arcsin((n0 / n1) * np.sin(theta0_rad))
        theta2_rad = np.lib.scimath.arcsin((n1 / n2) * np.sin(theta1_rad))

    r01_p = (n1 * np.cos(theta0_rad) - n0 * np.cos(theta1_rad)) / (n1 * np.cos(theta0_rad) + n0 * np.cos(theta1_rad))
    r12_p = (n2 * np.cos(theta1_rad) - n1 * np.cos(theta2_rad)) / (n2 * np.cos(theta1_rad) + n1 * np.cos(theta2_rad))
    beta = (2 * np.pi / (wavelength_range_nm * 1e-9)) * n1 * d * np.cos(theta1_rad)
    r_total_p = (r01_p + r12_p * np.exp(2j * beta)) / (1 + r01_p * r12_p * np.exp(2j * beta))

    reflectance = np.abs(r_total_p)**2
    reflectance = np.nan_to_num(reflectance) # Replace NaN with 0

    transmittance = 1.0 - reflectance
    return transmittance


def generate_dataset_from_pairs(param_pairs, wavelengths, material_config, data_dir, is_lhs=False):
    """
    Helper function to generate and save a dataset from (angle, thickness) pairs.
    *** MODIFICATION: Does NOT delete existing data. ***
    """
    full_data_dir = os.path.join(RESULTS_DIR, data_dir)
    if not os.path.exists(full_data_dir):
        os.makedirs(full_data_dir)
        print(f"Created directory: '{full_data_dir}/'")
    else:
        print(f"Data directory '{full_data_dir}/' already exists. Verifying files...")

    n_incident_func = lambda lam: np.ones_like(lam)
    n_film_func = load_material_data(material_config['film_csv'])
    n_substrate_func = load_material_data(material_config['substrate_csv'])

    files_created_count = 0
    for i, (angle, thickness) in enumerate(param_pairs):
        if is_lhs:
            filename = f"sample_{i+1:003d}_angle_{angle:.1f}_thickness_{thickness:.1f}.csv"
        else:
            filename = f"angle_{angle:.1f}_thickness_{thickness:.1f}.csv"

        filepath = os.path.join(full_data_dir, filename)

        # *** INCREMENTAL CHECK: Skip if file already exists ***
        if os.path.exists(filepath):
            continue

        transmittance = calculate_transmittance(wavelengths, angle, thickness, n_incident_func, n_film_func, n_substrate_func)
        transmittance_pct = transmittance * 100
        transmittance_error = 100.0 - transmittance_pct

        pd.DataFrame({
            'Wavelength (nm)': wavelengths,
            'P-Transmittance-Error (%)': transmittance_error # Save T_Error
        }).to_csv(filepath, index=False, float_format='%.6f')
        files_created_count += 1

    if files_created_count > 0:
        print(f"Successfully generated {files_created_count} new data files in '{full_data_dir}/'")
    else:
        print(f"All {len(param_pairs)} data files already exist in '{full_data_dir}/'. No new files created.")


def run_physics_simulation_and_data_generation(material_config):
    """
    Finds the true physical *transmittance* optimum and generates all datasets.
    *** MODIFICATION: Skips generation if files exist. ***
    """
    print("\n" + "="*80 + f"\nSECTION 1.1: PHYSICS SIMULATION FOR: {material_config['name']}\n" + "="*80)

    wavelengths = np.arange(400, 1201, 1) # This defines the output shape: 801
    n_incident_func = lambda lam: np.ones_like(lam)
    n_film_func = load_material_data(material_config['film_csv'])
    n_substrate_func = load_material_data(material_config['substrate_csv'])

    true_opt_filepath = os.path.join(RESULTS_DIR, f"{material_config['prefix']}_true_optimal_spectrum.csv")

    if not os.path.exists(true_opt_filepath):
        print("\n--- Searching for True Physical Optimum (Max Transmittance) ---")
        search_angles_fine, search_thicknesses_fine = np.arange(0, 61, 1), np.arange(30, 151, 1)
        best_max_transmittance = float('-inf')
        best_angle, best_thickness = -1, -1

        for angle in search_angles_fine:
            for thickness in search_thicknesses_fine:
                p_transmittance = calculate_transmittance(wavelengths, angle, thickness, n_incident_func, n_film_func, n_substrate_func)
                current_max_transmittance = np.max(p_transmittance)
                if current_max_transmittance > best_max_transmittance:
                    best_max_transmittance, best_angle, best_thickness = current_max_transmittance, angle, thickness

        print(f"True Optimum Found: Angle={best_angle}°, Thickness={best_thickness} nm")
        material_config['true_optimum'] = {'angle': best_angle, 'thickness': best_thickness}

        final_optimal_spectrum_T = calculate_transmittance(wavelengths, best_angle, best_thickness, n_incident_func, n_film_func, n_substrate_func)
        pd.DataFrame({
            'Wavelength (nm)': wavelengths,
            'True Transmittance (%)': final_optimal_spectrum_T * 100,
            'True Transmittance-Error (%)': 100.0 - (final_optimal_spectrum_T * 100)
        }).to_csv(true_opt_filepath, index=False)
    else:
        print("\n--- True Physical Optimum file found. Skipping search. ---")
        if material_config['prefix'] == 'mgf2':
            material_config['true_optimum'] = {'angle': 51.0, 'thickness': 148.0}
        elif material_config['prefix'] == 'sio2':
            material_config['true_optimum'] = {'angle': 54.0, 'thickness': 150.0}

    print("\n--- Verifying 500-sample dataset (LHS) ---")
    sampler = qmc.LatinHypercube(d=2, seed=42)
    samples = sampler.random(n=500)
    l_bounds = [0, 30]  # Angle: [0, 60], Thickness: [30, 150]
    u_bounds = [60, 150]
    scaled_samples = qmc.scale(samples, l_bounds, u_bounds)
    dl_param_pairs = np.round(scaled_samples, 1)
    generate_dataset_from_pairs(dl_param_pairs, wavelengths, material_config, f"{material_config['prefix']}_data", is_lhs=True)

    print("\n--- Verifying 56-sample dataset (OOD) ---")
    ood_angles = [2.5, 7.5, 12.5, 17.5, 22.5, 27.5, 32.5] # 7 angles
    ood_thicknesses = np.arange(35, 146, 15).astype(float) # 8 thicknesses
    ood_param_pairs = [(a, t) for a in ood_angles for t in ood_thicknesses] # 7 * 8 = 56 samples
    generate_dataset_from_pairs(ood_param_pairs, wavelengths, material_config, f"{material_config['prefix']}_ood_data", is_lhs=False)

    return wavelengths

